use std::fmt;

use serde::Serialize;
use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::domain::error::SwarmError;

const MAX_LOGICAL_ID_LEN: usize = 128;

/// Client-provided stable identity for one Swarm agent session.
///
/// Shape: `^[A-Za-z0-9_-]{1,128}$` (`design §2.2`). The value is the API path
/// segment and the Actor key component; it never changes for a session.
#[derive(Clone, Debug, Eq, PartialEq, Hash, Ord, PartialOrd, Serialize)]
#[serde(transparent)]
pub struct LogicalId(String);

impl LogicalId {
    pub fn parse(value: &str) -> Result<Self, SwarmError> {
        if value.is_empty() {
            return Err(SwarmError::invalid_logical_id("empty"));
        }
        if value.len() > MAX_LOGICAL_ID_LEN {
            return Err(SwarmError::invalid_logical_id("too long"));
        }
        if !value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        {
            return Err(SwarmError::invalid_logical_id(
                "only ASCII letters, digits, '-' and '_' are allowed",
            ));
        }
        Ok(Self(value.to_owned()))
    }

    /// Generate a fresh server-side identity for SDK clients that omit `logicalId`.
    #[must_use]
    pub fn generate() -> Self {
        Self(format!("agent-{}", Uuid::now_v7()))
    }

    /// Derive a deterministic identity from an `Idempotency-Key` header so SDK
    /// retries of `POST /sessions` address the same session.
    #[must_use]
    pub fn derived_from_idempotency_key(key: &str) -> Self {
        let digest = Sha256::digest(key.as_bytes());
        let hex: String = digest.iter().take(16).map(|b| format!("{b:02x}")).collect();
        Self(format!("agent-{hex}"))
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for LogicalId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl TryFrom<&str> for LogicalId {
    type Error = SwarmError;

    fn try_from(value: &str) -> Result<Self, Self::Error> {
        Self::parse(value)
    }
}

/// Rivet actor identity (`design §3.3`): name `swarm-session`, key `["agent", logicalId]`.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActorKey {
    logical_id: LogicalId,
}

impl ActorKey {
    pub const ACTOR_NAME: &'static str = "swarm-session";

    #[must_use]
    pub fn new(logical_id: LogicalId) -> Self {
        Self { logical_id }
    }

    #[must_use]
    pub fn logical_id(&self) -> &LogicalId {
        &self.logical_id
    }

    #[must_use]
    pub fn segments(&self) -> [&str; 2] {
        ["agent", self.logical_id.as_str()]
    }

    /// Stable text form persisted in `swarm_sessions.actor_key`.
    #[must_use]
    pub fn storage_key(&self) -> String {
        format!("agent/{}", self.logical_id.as_str())
    }
}

/// Runtime identity of one root ACP session. Generated by the host in S3; S4
/// passes a reserved id through `_meta["peri.rootSessionId"]`.
#[must_use]
pub fn new_root_session_id() -> String {
    Uuid::now_v7().to_string()
}

